// 二次曲線外推（年份超出表時使用）。
function extrapolateDeltaT(y, jsd) {
  const dy = (y - 1820) / 100;
  return -20 + jsd * dy * dy;
}

// 計算 ΔT（秒），傳入年份。
export function computeDeltaT(y) {
  const d = DELTA_T_TABLE;
  const y0 = d[d.length - 2]; // 表中最後一年
  const t0 = d[d.length - 1]; // 表中最後一年的 ΔT
  if (y >= y0) {
    const jsd = 31; // 二次外推的加速度；瑞士星曆表 31、NASA 32、skmap 29
    if (y > y0 + 100) return extrapolateDeltaT(y, jsd);
    const v = extrapolateDeltaT(y, jsd);
    const dv = extrapolateDeltaT(y0, jsd) - t0;
    return v - dv * (y0 + 100 - y) / 100;
  }
  let i;
  for (i = 0; i < d.length; i += 5) if (y < d[i + 5]) break;
  const t1 = (y - d[i]) / (d[i + 5] - d[i]) * 10;
  const t2 = t1 * t1, t3 = t2 * t1;
  return d[i + 1] + d[i + 2] * t1 + d[i + 3] * t2 + d[i + 4] * t3;
}

// 傳入儒略日（J2000 起算），回傳 ΔT（天）。
export function deltaT(t) {
  return computeDeltaT(t / 365.2425 + 2000) / 86400.0;
}
