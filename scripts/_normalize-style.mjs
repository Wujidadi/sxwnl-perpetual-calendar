function convertSimpToTrad(s) {
  let out = '';
  for (const ch of s) out += SIMP_TO_TRAD[ch] || ch;
  return out;
}

// 主轉換：以狀態機跳過字串／模板字串；
// - 在註釋區（//... 或 /* ... */）內：套用簡→繁、補註釋符空格、修整中綴空格。
// - 在程式碼區：補逗號後空格。
function transform(code) {
  let out = '';
  let i = 0;
  const n = code.length;

  while (i < n) {
    const c = code[i];
    const next = code[i + 1];

    // 行註釋
    if (c === '/' && next === '/') {
      // 蒐集到行尾
      let j = i + 2;
      while (j < n && code[j] !== '\n') j++;
      let body = code.substring(i + 2, j);
      // 補空格：若第一個字元不是空白且非空，前置空格
      if (body.length > 0 && !/^\s/.test(body)) body = ' ' + body;
      // 簡→繁
      body = convertSimpToTrad(body);
      // 補逗號後空格（註解內也適用，以保持風格一致）
      body = body.replace(/,(?![\s,])/g, ', ');
      out += '//' + body;
      i = j;
      continue;
    }

    // 區塊註釋
    if (c === '/' && next === '*') {
      let j = i + 2;
      while (j < n - 1 && !(code[j] === '*' && code[j + 1] === '/')) j++;
      let body = code.substring(i + 2, j);
      // 前置空格
      if (body.length > 0 && !/^\s/.test(body)) body = ' ' + body;
      // 尾隨空格
      if (body.length > 0 && !/\s$/.test(body)) body = body + ' ';
      // 簡→繁
      body = convertSimpToTrad(body);
      // 補逗號後空格
      body = body.replace(/,(?![\s,])/g, ', ');
      out += '/*' + body + '*/';
      i = j + 2;
      continue;
    }

    // 字串
    if (c === '"' || c === "'" || c === '`') {
      const quote = c;
      out += c;
      i++;
      while (i < n) {
        const cc = code[i];
        if (cc === '\\') {
          out += code[i] + (code[i + 1] || '');
          i += 2;
          continue;
        }
        if (cc === quote) {
          out += cc;
          i++;
          break;
        }
        // 範本字串內的 ${...} 不在本次調整範圍（保留原樣）
        out += cc;
        i++;
      }
      continue;
    }

    // 程式碼區的逗號：補上空格（若下個非換行字元不是空白）
    if (c === ',') {
      out += ',';
      i++;
      // 若下一個字元不是空白也不是換行，補一個空格
      if (i < n && code[i] !== ' ' && code[i] !== '\t' && code[i] !== '\n' && code[i] !== '\r') {
        out += ' ';
      }
      continue;
    }

    out += c;
    i++;
  }

  return out;
}

async function main() {
  for (const rel of TARGET_FILES) {
    const path = join(projectRoot, rel);
    const original = await readFile(path, 'utf-8');
    // 先統一行尾為 LF
    const lf = original.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
    const next = transform(lf);
    if (original !== next) {
      await writeFile(path, next, 'utf-8');
      console.log(`[updated] ${rel}`);
    } else {
      console.log(`[skip]    ${rel}`);
    }
  }
}

main().catch((err) => { console.error(err); process.exit(1); });
